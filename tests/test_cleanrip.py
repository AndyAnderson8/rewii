"""Tests for rewii.core.cleanrip with tiny synthetic dumps."""
from __future__ import annotations

import hashlib
import struct
import zlib

import pytest

from rewii.core import cleanrip as C
from rewii.core.disc import WII_MAGIC
from rewii.core.progress import Cancelled, CancelToken


def disc_bytes(n: int = 300_000) -> bytes:
    h = bytearray(0x400)
    h[:6] = b"RSPE01"
    h[0x18:0x1C] = struct.pack(">I", WII_MAGIC)
    h[0x20:0x2B] = b"Wii Sports\0"
    return bytes(h) + bytes(range(256)) * ((n - 0x400) // 256)


def dumpinfo(data: bytes, name: str = "RSPE01", *, md5: str | None = None) -> str:
    return ("--File Generated by CleanRip v2.2.1--\r\n\r\n"
            f"Filename: {name}\r\nInternal Name: Wii Sports\r\n"
            f"MD5: {md5 or hashlib.md5(data).hexdigest()}\r\n"
            f"SHA-1: {hashlib.sha1(data).hexdigest()}\r\n"
            f"CRC32: {zlib.crc32(data):08X}\r\nVersion: 1.00\r\nVerified: Yes\r\n"
            "Duration: 3 min. 2 sec\r\nDumped at: 2026-01-01 10:00:00.\r\n")


def make_split(folder, data: bytes, base: str = "RSPE01", parts: int = 3, info: str | None = None):
    size = -(-len(data) // parts)
    for i in range(parts):
        (folder / f"{base}.part{i}.iso").write_bytes(data[i * size:(i + 1) * size])
    (folder / f"{base}-dumpinfo.txt").write_text(info if info is not None else dumpinfo(data, base))
    (folder / f"{base}.bca").write_bytes(bytes(64))


def test_parse_dumpinfo(tmp_path):
    data = disc_bytes()
    p = tmp_path / "RSPE01-dumpinfo.txt"
    p.write_text(dumpinfo(data))
    info = C.parse_dumpinfo(p)
    assert info.filename == "RSPE01" and info.internal_name == "Wii Sports"
    assert info.md5 == hashlib.md5(data).hexdigest()
    assert info.crc32 == f"{zlib.crc32(data):08x}"
    assert info.verified is True


def test_find_and_join(tmp_path):
    data = disc_bytes()
    make_split(tmp_path, data)
    make_split(tmp_path, data[:1000] + b"x" * 5000, base="GALE01-disc2", parts=2)
    single = tmp_path / "Wii Play (USA).iso"
    single.write_bytes(data)
    (tmp_path / "Wii Play (USA)-dumpinfo.txt").write_text(dumpinfo(data, "Wii Play (USA)"))
    (tmp_path / "plain.iso").write_bytes(data)          # no dumpinfo -> not a CleanRip dump
    dumps = {d.name: d for d in C.find_dumps(tmp_path)}
    assert set(dumps) == {"RSPE01", "GALE01-disc2", "Wii Play (USA)"}
    d = dumps["RSPE01"]
    assert len(d.parts) == 3 and d.bca and d.dumpinfo and d.complete and d.is_split
    assert not dumps["Wii Play (USA)"].is_split

    events = []
    res = C.join_dump(d, tmp_path / "out" / "RSPE01.iso", progress=events.append)
    assert res.ok and res.dumpinfo_match is True
    assert (tmp_path / "out" / "RSPE01.iso").read_bytes() == data
    assert res.platform == "wii" and res.game_id == "RSPE01"
    assert events[-1].done == events[-1].total == len(data)

    v = C.verify_dump(dumps["Wii Play (USA)"])
    assert v.ok and v.dumpinfo_match


def test_mismatch_and_missing_part(tmp_path):
    data = disc_bytes()
    make_split(tmp_path, data, info=dumpinfo(data, md5="0" * 32))
    d = C.find_dumps(tmp_path)[0]
    res = C.join_dump(d, tmp_path / "j.iso")
    assert not res.ok and res.dumpinfo_match is False and "MD5" in res.mismatches[0]
    (tmp_path / "RSPE01.part1.iso").unlink()
    d = C.find_dumps(tmp_path)[0]
    assert d.missing_parts == [1] and not d.complete
    with pytest.raises(C.CleanRipError):
        C.join_dump(d, tmp_path / "j2.iso")


def test_redump_dat(tmp_path):
    data = disc_bytes()
    make_split(tmp_path, data)
    (tmp_path / "wii.dat").write_text(
        '<?xml version="1.0"?><datafile><header><name>Nintendo - Wii</name></header>'
        f'<game name="Wii Sports (Europe)"><rom name="Wii Sports (Europe).iso" size="{len(data)}" '
        f'crc="{zlib.crc32(data):08x}" md5="{hashlib.md5(data).hexdigest()}" '
        f'sha1="{hashlib.sha1(data).hexdigest()}"/></game></datafile>')
    res = C.join_dump(C.find_dumps(tmp_path)[0], tmp_path / "o.iso")
    assert res.dat_checked and res.redump_name == "Wii Sports (Europe)"
    res2 = C.verify_dump(C.find_dumps(tmp_path)[0], use_dat=False)
    assert not res2.dat_checked and res2.redump_name is None


def test_join_cancel(tmp_path):
    make_split(tmp_path, disc_bytes())
    tok = CancelToken()
    tok.cancel()
    with pytest.raises(Cancelled):
        C.join_dump(C.find_dumps(tmp_path)[0], tmp_path / "c.iso", cancel=tok)
    assert not list(tmp_path.glob("c.iso*"))
